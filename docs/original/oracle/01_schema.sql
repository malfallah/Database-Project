-- 1. EMPLOYEE
CREATE TABLE EMPLOYEE
(
Employee_ID INT PRIMARY KEY CHECK (EMPLOYEE_ID>9999),
Fname VARCHAR(15) NOT NULL,
Mname VARCHAR(15) NOT NULL,
Lname VARCHAR(15) NOT NULL,
Salary FLOAT DEFAULT ‘6000’ CHECK (SALARY>5000),
BDate DATE DEFAULT ‘1950-01-01’,
Gender VARCHAR(6) CHECK (GENDER IN (‘Male’,’Female’,NULL)),
Super_ID INT,
Role VARCHAR(15) NOT NULL,
FOREIGN KEY (Super_ID) REFERENCES EMPLOYEE(Employee_ID)
);

-- 2. CUSTOMER
CREATE TABLE CUSTOMER
(
Customer_ID INT PRIMARY KEY CHECK (CUSTOMER_ID>9999),
Fname VARCHAR(15) NOT NULL,
Mname VARCHAR(15) NOT NULL,
Lname VARCHAR(15) NOT NULL,
Satisfaction INT CHECK (SATISFACTION BETWEEN 0 AND 10),
Gender VARCHAR(6) NOT NULL CHECK (GENDER IN (‘Male’,’Female’,NULL)),
VSN INT,
HTitle VARCHAR(100),
FOREIGN KEY (VSN) REFERENCES VEHICLE(SN),
FOREIGN KEY (HTitle) REFERENCES HOUSE(Title_dead) );

-- 3. DEPARTMENT
CREATE TABLE DEPARTMENT
(
DName VARCHAR(30) NOT NULL,
DNumber INT PRIMARY KEY CHECK (DNUMBER>0),
Number_of_employees INT NOT NULL CHECK(NUMBER_OF_EMPLOYEES>0),
Number_of_customers INT NOT NULL CHECK (NUMBER_OF_CUSTOMERS>0),
EID INT,
Manager_Start_Date DATE NOT NULL;
FOREIGN KEY (EID) REFERENCES EMPLOYEE(Employee_ID)
);

-- 4. INSURANCE
CREATE TABLE INSURANCE
(
IID INT PRIMARY KEY CHECK(IID>0),
Coverage INT DEFAULT 30 CHECK (COVERAGE BETWEEN 30 AND 100),
Type_of_Insurance VARCHAR(20) NOT NULL CHECK (TYPE_OF_INSURANCE IN
(‘Mandatory’,’Against others’,’Other’)),
);

-- 5. HOUSE
CREATE TABLE HOUSE
(
Title_dead VARCHAR(100) PRIMARY KEY,
VCollectibles FLOAT,
TCollectibles VARCHAR(30),
QCollectibles INT,
MCollectibles VARCHAR(30),
Area FLOAT NOT NULL,
Year_built INT NOT NULL,
Value FLOAT NOT NULL CHECK (VALUE>5000),
IID INT,
Percentage FLOAT DEFAULT 30 CHECK (PERCENTAGE BETWEEN 30 AND 100),
FOREIGN KEY (IID) REFERENCES INSURANCE (IID)
);

-- 6. VEHICLE
CREATE TABLE VEHICLE
(
SN INT PRIMARY KEY CHECK (SN>99999),
State CHAR(1) CHECK (STATE BETWEEN ‘A’ AND ‘Z’),
Year INT NOT NULL,
Make VARCHAR(15) NOT NULL,
Value FLOAT NOT NULL,
Model VARCHAR(15) NOT NULL,
Reg# INT,
IID INT,
Percentage FLOAT DEFAULT 30 CHECK (PERCENTAGE BETWEEN 30 AND 100),
FOREIGN KEY (IID) REFERENCES INSURANCE (IID) );

-- 7. PAYMENT
CREATE TABLE PAYMENT
(
Paid FLOAT NOT NULL CHECK (PAID>0),
Type VARCHAR(15) NOT NULL CHECK (TYPE IN (‘INSTALLMENT’,’LUNP SUM’)),
Bill FLOAT NOT NULL CHECK (BILL>0),
Mechanism VARCHAR(20) NOT NULL,
ReceiptNo INT PRIMARY KEY CHECK (RECEIPTNO>0),
CID INT,
FOREIGN KEY (CID) REFERENCES CUSTOMER(Customer_ID)
);

-- 8. EXPENSE
CREATE TABLE EXPENSE
(
Item VARCHAR(30) NOT NULL,
Price REAL NOT NULL,
RNumber INT PRIMARY KEY CHECK (RNUMBER>0),
Date DATE NOT NULL,
Type_of_Item VARCHAR(30) NOT NULL,
);

-- 9. CONTRACTING_COMPANY
CREATE TABLE CONTRACTING_COMPANY
(
CName VARCHAR(30) PRIMARY KEY,
Service VARCHAR(20) NOT NULL, );

-- 10. HEALTH
CREATE TABLE HEALTH
(
ReportNo INT PRIMARY KEY CHECK (REPORTNO>0),
Exit_Date DATE NOT NULL,
Enter_Date DATE NOT NULL,
Hospital_Name VARCHAR(30) NOT NULL,
CID CHAR(9) NOT NULL,
HBoolean CHAR(1) CHECK (HBoolean IN (‘T’,’F’)),
IID INT NOT NULL,
Percentage FLOAT NOT NULL CHECK (PERCENTAGE BETWEEN 30 AND
100),
FOREIGN KEY (CID) REFERENCES CUSTOMER (Customer_ID),
FOREIGN KEY (IID) REFERENCES INSURANCE (IID)
);

-- 11. DEPENDENT
CREATE TABLE DEPENDENT
(
Gender VARCHAR(6) CHECK (GENDER IN (‘Male’,’Female’,NULL)),
BDate DATE DEFAULT ‘1950-01-01’,
Relationship VARCHAR(10) NOT NULL,
Name VARCHAR(15),
EID INT,
PRIMARY KEY (Name,EID),
FOREIGN KEY (EID) REFERENCES EMPLOYEE (Employee_ID)
);

-- 12. MEDICAL_RECORD
CREATE TABLE MEDICAL_RECORD
(
Blood_Type VARCHAR(3) DEFAULT 'O+' CHECK (Blood_Type IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
Weight FLOAT NOT NULL CHECK (Weight>=3),
Height FLOAT NOT NULL CHECK (Height>=40),
Age INT NOT NULL CHECK (Age BETWEEN 1 AND
130),
Sex VARCHAR(6) CHECK (Sex IN ('Male','Female',NULL)),
Disease VARCHAR(20),
Allergy VARCHAR(20),
RecordNo INT CHECK (RecordNo>0),
CID INT,
PRIMARY KEY (RecordNo,CID),
FOREIGN KEY (CID) REFERENCES CUSTOMER (Customer_ID)
);

